// Bundles the MCP App view into one self-contained HTML string (src/view.generated.mjs)
// and copies the shared card renderer into the simulator (web/render.js).
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = await build({
  entryPoints: [path.join(root, 'src/view/app.js')], bundle: true, format: 'esm', write: false,
  minify: true, target: 'es2022', platform: 'browser', legalComments: 'none',
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html lang="en-AU"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">` +
  `<title>Streamday</title></head><body><div id="root" class="sd-root"></div><script type="module">${js}</script></body></html>`;
fs.writeFileSync(path.join(root, 'src/view.generated.mjs'),
  `// Generated by scripts/build-view.mjs — do not edit. Source: src/view/app.js + src/view/render.js\nexport const VIEW_HTML = ${JSON.stringify(html)};\n`);
fs.mkdirSync(path.join(root, 'web'), { recursive: true });
fs.copyFileSync(path.join(root, 'src/view/render.js'), path.join(root, 'web/render.js'));
console.log(`view: ${(html.length / 1024).toFixed(0)} KB`);
